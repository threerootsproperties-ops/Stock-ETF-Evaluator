            tbl = [["Quarter ended", "Reported on", "EPS", "Consensus estimate", "Surprise"]]
            for e in cx["earnings"]:
                tbl.append([e["quarter"], e["reported"], ratio(e["eps"]), ratio(e["estimate"]),
                            pct(e["surprise_pct"] / 100, 0, True) if e["surprise_pct"] is not None else NA])
